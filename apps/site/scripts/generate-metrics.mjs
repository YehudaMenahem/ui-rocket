#!/usr/bin/env node
/**
 * Derives real showcase metrics from the repo. Never invents numbers.
 * Writes apps/site/src/data/metrics.generated.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../../..');
const rocketSrc = path.join(root, 'packages/rocket/src');
const rocketDist = path.join(root, 'packages/rocket/dist');
const outFile = path.join(root, 'apps/site/src/data/metrics.generated.ts');

const COMPONENT_IDS = {
  button: { file: 'Button.tsx', test: 'Button.test.tsx', exportName: 'Button' },
  input: { file: 'InputField.tsx', test: 'InputField.test.tsx', exportName: 'InputField' },
  checkbox: { file: 'Checkbox.tsx', test: 'Checkbox.test.tsx', exportName: 'Checkbox' },
  radio: { file: 'RadioButton.tsx', test: null, exportName: 'RadioButton' },
  toggle: { file: 'ToggleButton.tsx', test: null, exportName: 'ToggleButton' },
  select: { file: 'SelectField.tsx', test: null, exportName: 'SelectField' },
  textbox: { file: 'Textbox.tsx', test: null, exportName: 'Textbox' },
  icon: { file: 'Icon.tsx', test: null, exportName: 'Icon' },
  img: { file: 'Img.tsx', test: 'Img.test.tsx', exportName: 'Img' },
  tabs: { file: 'Tabs.tsx', test: 'Tabs.test.tsx', exportName: 'Tabs' },
  form: { file: 'Form.tsx', test: null, exportName: 'Form' },
  modal: { file: 'Modal.tsx', test: null, exportName: 'Modal' },
  toaster: { file: 'Toaster.tsx', test: null, exportName: 'Toaster' },
};

function countTests(filePath) {
  if (!filePath || !fs.existsSync(filePath)) return 0;
  const src = fs.readFileSync(filePath, 'utf8');
  const matches = src.match(/\b(?:test|it)\s*\(/g);
  return matches ? matches.length : 0;
}

function gzipBytes(filePath) {
  if (!fs.existsSync(filePath)) return null;
  const buf = fs.readFileSync(filePath);
  return zlib.gzipSync(buf).length;
}

function formatBytes(n) {
  if (n == null) return null;
  if (n < 1024) return `${n} B`;
  const kb = n / 1024;
  if (kb < 100) return `${kb.toFixed(1)} kB`;
  return `${Math.round(kb)} kB`;
}

const indexSrc = fs.readFileSync(path.join(rocketSrc, 'index.ts'), 'utf8');
const exportNames = [...indexSrc.matchAll(/export\s+\{\s*(\w+)\s*\}/g)].map((m) => m[1]);
const componentCount = exportNames.length;

const perComponent = {};
let totalTests = 0;
for (const [id, meta] of Object.entries(COMPONENT_IDS)) {
  const tests = countTests(meta.test ? path.join(rocketSrc, meta.test) : null);
  totalTests += tests;
  perComponent[id] = {
    exportName: meta.exportName,
    tests,
    testsLabel: tests === 1 ? '1 test' : `${tests} tests`,
  };
}

const jsGzip = gzipBytes(path.join(rocketDist, 'index.js'));
const cssGzip = gzipBytes(path.join(rocketDist, 'rocket.css'));
const bundleGzip =
  jsGzip != null && cssGzip != null ? jsGzip + cssGzip : jsGzip ?? cssGzip ?? null;

const tsFiles = fs
  .readdirSync(rocketSrc)
  .filter((f) => /\.(ts|tsx)$/.test(f) && !f.endsWith('.d.ts'));
const jsFiles = fs.readdirSync(rocketSrc).filter((f) => /\.(js|jsx)$/.test(f));
const typedPct =
  tsFiles.length + jsFiles.length === 0
    ? null
    : Math.round((tsFiles.length / (tsFiles.length + jsFiles.length)) * 100);

const generated = `// AUTO-GENERATED by apps/site/scripts/generate-metrics.mjs — do not edit.
// Run: node apps/site/scripts/generate-metrics.mjs (also via Vite plugin / prebuild)

export const METRICS = {
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  componentCount: ${componentCount},
  exportNames: ${JSON.stringify(exportNames)} as const,
  totalTests: ${totalTests},
  bundleGzipBytes: ${bundleGzip == null ? 'null' : bundleGzip},
  bundleGzipLabel: ${JSON.stringify(bundleGzip == null ? null : `${formatBytes(bundleGzip)} gzip`)},
  jsGzipBytes: ${jsGzip == null ? 'null' : jsGzip},
  cssGzipBytes: ${cssGzip == null ? 'null' : cssGzip},
  typedPct: ${typedPct == null ? 'null' : typedPct},
  license: 'MIT',
  perComponent: ${JSON.stringify(perComponent, null, 2)} as const,
} as const;

export type Metrics = typeof METRICS;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, generated);
console.log(
  `[metrics] components=${componentCount} tests=${totalTests} bundleGzip=${formatBytes(bundleGzip)} → ${path.relative(root, outFile)}`
);
